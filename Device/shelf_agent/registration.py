"""Matching a configured device with its row in the backend.

The backend generates device ids (``POST /devices``) and has no lookup by key,
so on start-up the agent lists ``GET /devices``, finds its ``deviceKey`` and
checks that the backend links it to the configured shelf. The emulator can
also register missing devices, which makes a demo setup one command.
"""

from __future__ import annotations

import logging
import threading
from dataclasses import replace

from shelf_agent.config import DeviceIdentity
from shelf_agent.transport.client import BackendClient, BackendError

logger = logging.getLogger(__name__)


class RegistrationError(Exception):
    """The backend's view of this device contradicts the config. Not retryable."""


def resolve_identity(client: BackendClient, *, register: bool) -> DeviceIdentity:
    """Find (or create) this device in the backend and bind its id to ``client``.

    Args:
        client: Client configured with the device key and shelf id.
        register: Create the device with ``POST /devices`` if it is missing.

    Returns:
        The identity with the backend's ``device_id``.

    Raises:
        RegistrationError: Unknown key with ``register`` off, or the key is
            bound to another shelf/id than configured.
        BackendError: The backend could not be reached or refused a request.
    """
    wanted = client.identity
    match = next(
        (d for d in client.list_devices() if d.device_key == wanted.device_key), None
    )

    if match is None:
        if wanted.device_id is not None:
            raise RegistrationError(
                f"device_id = {wanted.device_id} is configured, but key "
                f"'{wanted.device_key}' is not registered in the backend. Ids are "
                "generated by the backend: remove device_id and let the agent "
                "look it up (or register it)"
            )
        if not register:
            raise RegistrationError(
                f"device key '{wanted.device_key}' is not registered in the backend. "
                f'Create it: POST /devices {{"deviceKey": "{wanted.device_key}", '
                f'"shelfId": {wanted.shelf_id}}}, or enable registration'
            )
        resolved = replace(wanted, device_id=client.register_device())
        logger.info(
            "registered device '%s' on shelf %s as id %s",
            wanted.device_key,
            wanted.shelf_id,
            resolved.device_id,
        )
    else:
        if match.shelf_id != wanted.shelf_id:
            raise RegistrationError(
                f"device '{wanted.device_key}' is linked to shelf {match.shelf_id} "
                f"in the backend, but configured for shelf {wanted.shelf_id}"
            )
        if wanted.device_id is not None and wanted.device_id != match.id:
            raise RegistrationError(
                f"device '{wanted.device_key}' has id {match.id} in the backend, "
                f"but device_id = {wanted.device_id} is configured"
            )
        if match.status not in (None, "ACTIVE"):
            logger.warning(
                "device '%s' (id %s) is %s in the backend",
                wanted.device_key,
                match.id,
                match.status,
            )
        resolved = replace(wanted, device_id=match.id)

    client.bind(resolved)
    return resolved


def connect(
    client: BackendClient,
    *,
    register: bool,
    stop: threading.Event,
    retry_s: float,
    wait: bool = True,
) -> bool:
    """Resolve the identity, tolerating an unreachable backend.

    If the backend is down but ``device_id`` is configured, the agent starts
    anyway and frames queue in the outbox. Without an id there is nothing to
    send under, so a device (``wait=True``) retries until the backend answers;
    the emulator (``wait=False``) gives up immediately.

    Returns:
        ``True`` when the agent can start, ``False`` if ``stop`` was set.

    Raises:
        RegistrationError: See :func:`resolve_identity`.
        BackendError: A non-retryable error, or the backend is down with
            ``wait=False`` and no configured ``device_id``.
    """
    while not stop.is_set():
        try:
            resolve_identity(client, register=register)
            return True
        except BackendError as exc:
            if not exc.retryable:
                raise
            if client.identity.device_id is not None:
                logger.warning(
                    "backend unreachable (%s); starting as device %s, "
                    "frames will queue until it is back",
                    exc,
                    client.identity.device_id,
                )
                return True
            if not wait:
                raise
            logger.warning("backend unreachable (%s); retrying in %ss", exc, retry_s)
            stop.wait(retry_s)
    return False
