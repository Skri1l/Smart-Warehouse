"""Configuration of a real shelf device, loaded from a TOML file.

Secrets (the device key) are read from an environment variable rather than
the file, so a config can be committed as a template (NFR-03).
"""

from __future__ import annotations

import os
import tomllib
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

# Endpoints as published by the backend's OpenAPI spec (/v3/api-docs).
DEFAULT_IMAGE_EVENTS_PATH = "/image-events"
DEFAULT_DEVICES_PATH = "/devices"
DEFAULT_HEARTBEAT_PATH = "/devices/{device_id}/heartbeat"
# Image upload that runs recognition and updates the shelf stock.
DEFAULT_DEVICE_IMAGES_PATH = "/devices/{device_id}/images"
# RFC-0001 multipart upload; not implemented by the backend yet.
DEFAULT_UPLOAD_PATH = "/api/v1/device-events/images"
DEFAULT_DEVICE_KEY_ENV = "SW_DEVICE_KEY"

PROTOCOL_IMAGE_EVENTS = "image-events"
PROTOCOL_DEVICE_IMAGES = "device-images"
PROTOCOL_MULTIPART = "multipart"
PROTOCOLS = (PROTOCOL_IMAGE_EVENTS, PROTOCOL_DEVICE_IMAGES, PROTOCOL_MULTIPART)
TIMESTAMP_ZONES = ("local", "utc")


class ConfigError(ValueError):
    """Raised when a config or scenario file is missing data or is invalid."""


@dataclass(frozen=True)
class BackendConfig:
    """Where and how the agent reaches the backend.

    Attributes:
        base_url: Backend origin, e.g. ``http://192.168.1.10:8080``.
        protocol: ``image-events`` sends JSON to ``POST /image-events`` as
            published in Swagger (the image stays on the device, its path is
            sent). ``device-images`` uploads the file to
            ``POST /devices/{id}/images``: the backend runs recognition and
            writes the counted quantity to the shelf stock. ``multipart``
            uploads the file itself (RFC-0001), once the backend implements
            that endpoint.
        image_events_path: ``POST`` endpoint for ``image-events``.
        device_images_path: ``POST`` endpoint for ``device-images``;
            ``{device_id}`` is substituted.
        upload_path: ``POST`` endpoint for ``multipart``.
        devices_path: Device collection, used to look the device up by key.
        heartbeat_path: Heartbeat endpoint; ``{device_id}`` is substituted.
        timestamp_zone: Zone of ``capturedAt`` for ``image-events`` and
            ``device-images``. The
            backend stores a ``LocalDateTime`` and stamps ``receivedAt`` with
            its own local clock, so ``local`` keeps both comparable.
        timeout_s: Per-request timeout in seconds.
    """

    base_url: str
    protocol: str = PROTOCOL_IMAGE_EVENTS
    image_events_path: str = DEFAULT_IMAGE_EVENTS_PATH
    device_images_path: str = DEFAULT_DEVICE_IMAGES_PATH
    upload_path: str = DEFAULT_UPLOAD_PATH
    devices_path: str = DEFAULT_DEVICES_PATH
    heartbeat_path: str = DEFAULT_HEARTBEAT_PATH
    timestamp_zone: str = "local"
    timeout_s: float = 10.0


@dataclass(frozen=True)
class DeviceIdentity:
    """How a device identifies itself to the backend (``Device`` entity).

    ``device_id`` is generated by the backend (``POST /devices``). It may be
    left out of the config; the agent then looks it up by ``device_key`` at
    start-up (see :mod:`shelf_agent.registration`).
    """

    device_id: int | None
    shelf_id: int
    device_key: str


@dataclass(frozen=True)
class CameraConfig:
    """Image source. ``type`` is ``picamera`` on the device, ``folder`` on a PC."""

    type: str = "picamera"
    width: int = 2304
    height: int = 1296
    folder: Path | None = None
    loop: bool = False
    capture_dir: Path | None = None


@dataclass(frozen=True)
class TriggerConfig:
    """What starts a capture: ``gpio`` sensor, ``interval`` timer or ``manual``."""

    type: str = "interval"
    interval_s: float = 60.0
    pin: int = 17
    settle_s: float = 2.0


@dataclass(frozen=True)
class DeviceConfig:
    """Complete configuration of one shelf agent process."""

    backend: BackendConfig
    identity: DeviceIdentity
    camera: CameraConfig
    trigger: TriggerConfig
    outbox_dir: Path
    heartbeat_interval_s: float = 30.0
    register: bool = False


def load_device_config(
    path: Path, env: Mapping[str, str] | None = None
) -> DeviceConfig:
    """Load a device config file.

    Relative paths inside the file are resolved against the file's directory.

    Args:
        path: TOML config file.
        env: Environment to read the device key from; defaults to ``os.environ``.

    Returns:
        The parsed configuration.

    Raises:
        ConfigError: If a required value is missing or has the wrong type.
    """
    env = os.environ if env is None else env
    raw = _read_toml(path)
    base_dir = path.parent

    device = _table(raw, "device")
    camera = raw.get("camera", {})
    trigger = raw.get("trigger", {})
    folder = camera.get("folder")
    capture_dir = camera.get("capture_dir", ".captures")

    return DeviceConfig(
        backend=parse_backend(_table(raw, "backend")),
        identity=DeviceIdentity(
            device_id=_optional_int(device, "device_id"),
            shelf_id=_int(device, "shelf_id"),
            device_key=_device_key(device, env),
        ),
        camera=CameraConfig(
            type=str(camera.get("type", "picamera")),
            width=int(camera.get("width", 2304)),
            height=int(camera.get("height", 1296)),
            folder=resolve_path(base_dir, folder) if folder else None,
            loop=bool(camera.get("loop", False)),
            capture_dir=resolve_path(base_dir, capture_dir),
        ),
        trigger=TriggerConfig(
            type=str(trigger.get("type", "interval")),
            interval_s=float(trigger.get("interval_s", 60.0)),
            pin=int(trigger.get("pin", 17)),
            settle_s=float(trigger.get("settle_s", 2.0)),
        ),
        outbox_dir=resolve_path(base_dir, device.get("outbox_dir", ".outbox")),
        heartbeat_interval_s=float(device.get("heartbeat_interval_s", 30.0)),
        register=bool(device.get("register", False)),
    )


def parse_backend(table: Mapping[str, Any]) -> BackendConfig:
    """Build a :class:`BackendConfig` from a ``[backend]`` TOML table."""
    if "base_url" not in table:
        raise ConfigError("[backend] base_url is required")
    protocol = str(table.get("protocol", PROTOCOL_IMAGE_EVENTS))
    if protocol not in PROTOCOLS:
        raise ConfigError(f"[backend] protocol must be one of {PROTOCOLS}")
    zone = str(table.get("timestamp_zone", "local"))
    if zone not in TIMESTAMP_ZONES:
        raise ConfigError(f"[backend] timestamp_zone must be one of {TIMESTAMP_ZONES}")
    return BackendConfig(
        base_url=str(table["base_url"]).rstrip("/"),
        protocol=protocol,
        image_events_path=str(
            table.get("image_events_path", DEFAULT_IMAGE_EVENTS_PATH)
        ),
        device_images_path=str(
            table.get("device_images_path", DEFAULT_DEVICE_IMAGES_PATH)
        ),
        upload_path=str(table.get("upload_path", DEFAULT_UPLOAD_PATH)),
        devices_path=str(table.get("devices_path", DEFAULT_DEVICES_PATH)),
        heartbeat_path=str(table.get("heartbeat_path", DEFAULT_HEARTBEAT_PATH)),
        timestamp_zone=zone,
        timeout_s=float(table.get("timeout_s", 10.0)),
    )


def resolve_path(base_dir: Path, value: str | Path) -> Path:
    """Resolve ``value`` against ``base_dir`` unless it is already absolute."""
    path = Path(value)
    return path if path.is_absolute() else (base_dir / path).resolve()


def _read_toml(path: Path) -> dict[str, Any]:
    try:
        with path.open("rb") as file:
            return tomllib.load(file)
    except FileNotFoundError as exc:
        raise ConfigError(f"config file not found: {path}") from exc
    except tomllib.TOMLDecodeError as exc:
        raise ConfigError(f"{path}: {exc}") from exc


def _table(raw: Mapping[str, Any], name: str) -> Mapping[str, Any]:
    table = raw.get(name)
    if not isinstance(table, Mapping):
        raise ConfigError(f"[{name}] section is required")
    return table


def _optional_int(table: Mapping[str, Any], key: str) -> int | None:
    return _int(table, key) if key in table else None


def _int(table: Mapping[str, Any], key: str) -> int:
    value = table.get(key)
    if not isinstance(value, int) or isinstance(value, bool):
        raise ConfigError(f"'{key}' must be an integer, got {value!r}")
    return value


def _device_key(device: Mapping[str, Any], env: Mapping[str, str]) -> str:
    env_name = str(device.get("device_key_env", DEFAULT_DEVICE_KEY_ENV))
    key = env.get(env_name) or device.get("device_key")
    if not key:
        raise ConfigError(
            f"device key is missing: set the {env_name} environment variable"
        )
    return str(key)
